function generateAll() {
  const baseDir = path.join(__dirname, '..', 'content', 'column');
  const thumbsDir = path.join(__dirname, '..', 'static', 'thumbnails');
  const fontsDir = path.join(__dirname, 'fonts');

  if (!fs.existsSync(thumbsDir)) fs.mkdirSync(thumbsDir, { recursive: true });

  console.log(`🚀 [Part 2 추가 칼럼 생성 시작] 총 ${newColumns.length}편의 고품질 임상 칼럼 생성 및 썸네일 렌더링...`);

  newColumns.forEach((col, idx) => {
    const colDir = path.join(baseDir, col.slug);
    if (!fs.existsSync(colDir)) fs.mkdirSync(colDir, { recursive: true });

    // Build Frontmatter & Markdown
    const voiceLines = col.voice.map(v => `  <p class="voice-desc">${v}</p>`).join('\n');
    const introParagraphs = col.intro.map(p => `<p class="column-p leading-relaxed text-slate-700 mb-4">${p}</p>`).join('\n\n');
    const tocItems = col.sections.map(s => `    <li>• ${s.heading}</li>`).join('\n');
    const sectionBlocks = col.sections.map(s => `### ${s.heading}\n\n${s.content}`).join('\n\n');

    const mdContent = `---
title: "${col.title}"
date: ${col.date}
category: "${col.category}"
tags: [${col.tags.map(t => `"${t}"`).join(', ')}]
thumbnail: "/thumbnails/${col.slug}.png"
summary: "${col.summary}"
---

<div class="column-voice-box">
  <div class="voice-title"><i class="fa-solid fa-comment-medical"></i> 진료실에서 자주 듣는 환자분들의 호소</div>
${voiceLines}
</div>

${introParagraphs}

<div class="column-toc-box my-8 p-6 bg-slate-50 border border-slate-200 rounded-xl">
  <h4 class="font-bold text-slate-900 mb-3 text-base"><i class="fa-solid fa-list-check mr-2 text-[#2F5D50]"></i> 이 칼럼에서 다루는 핵심 내용</h4>
  <ul class="space-y-2 text-sm text-slate-700">
${tocItems}
  </ul>
</div>

${sectionBlocks}
`;

    // Save Markdown
    fs.writeFileSync(path.join(colDir, 'index.md'), mdContent, 'utf8');

    // Generate Clean 1:1 SVG & PNG
    const svg = generateCleanCardSVG({
      slug: col.slug,
      title: col.title,
      category: col.category
    });

    const resvg = new Resvg(svg, {
      fitTo: { mode: 'width', value: 900 },
      font: {
        fontDirs: [fontsDir, 'C:\\Windows\\Fonts'],
        loadSystemFonts: true,
        defaultFontFamily: 'Pretendard'
      }
    });

    const pngBuffer = resvg.render().asPng();
    fs.writeFileSync(path.join(thumbsDir, `${col.slug}.svg`), svg, 'utf8');
    fs.writeFileSync(path.join(thumbsDir, `${col.slug}.png`), pngBuffer);

    console.log(`[${idx + 1}/${newColumns.length}] ✅ "${col.title}" (${col.slug}) 생성 완료!`);
  });

  console.log(`\n🎉 모든 Part 2 추가 칼럼 및 썸네일 생성이 무결점으로 완료되었습니다!`);
}

generateAll();
